#include "log.h"

/* ================================================================
 * log_init: 初始化 RTT 控制块
 *
 * 说明: _SEGGER_RTT 这个全局变量是"未初始化"的(放在 .bss),
 *       "SEGGER RTT" 这个 16 字节 ID 是在 _DoInit() 里运行时倒序写进去的。
 *       所以:
 *         - 上电瞬间控制块里还是全 0, 主机扫不到
 *         - 必须调用 SEGGER_RTT_Init() (或第一次 RTT 写操作隐式触发)
 *           之后, 主机才能发现它
 *       放在 main() 最开头调用, 可以把"控制块可见"这个时间点提前,
 *       让主机几乎一复位就能连上, 不会漏掉最早的几条日志。
 * ================================================================ */
void log_init(void)
{
    SEGGER_RTT_Init();
}
